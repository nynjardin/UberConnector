function setLang(lang) {
  LANG = lang === "en" ? "en" : "fr";
  document.documentElement.lang = LANG;
}

// `fr` in the current language, with `{name}` replaced from `vars`.
function t(fr, vars) {
  let s = (LANG === "en" && EN[fr]) || fr;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

// Translates the static texts of the page (text nodes and a few attributes).
function translatePage(root) {
  if (LANG === "fr") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const key = n.nodeValue.replace(/\s+/g, " ").trim();
    if (key && EN[key]) n.nodeValue = n.nodeValue.replace(/\S[\s\S]*\S|\S/, EN[key]);
  }
  for (const attr of ["title", "placeholder", "aria-label"]) {
    root.querySelectorAll(`[${attr}]`).forEach((e) => {
      const v = e.getAttribute(attr);
      if (EN[v]) e.setAttribute(attr, EN[v]);
    });
  }
}
